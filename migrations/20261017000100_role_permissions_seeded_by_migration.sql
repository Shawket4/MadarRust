-- DB audit 2026-10-16, Phase 4: stop the legacy reseed on boot.
--
-- Until now every boot ran `permissions::seeder::seed_role_permissions`, an
-- `INSERT ... ON CONFLICT DO NOTHING` of the global legacy role defaults. The
-- server no longer reads `role_permissions` to decide anything (the single
-- model decides), but two things still do:
--   * `authz_ensure_org_roles`, which seeds a legacy-template org's system
--     roles from it (orgs created outside `orgs::provision`: the demo
--     playground, hand-made orgs, test fixtures);
--   * `GET /permissions/roles` and the permission matrix (old editor routes).
-- So the rows must still exist on a database migrated from scratch. This
-- migration is that seed, once, with exactly the rows the boot seeder held
-- (generated from src/permissions/seeder.rs at this commit, 292 rows).
--
-- Idempotent and no-op on prod: every row already exists there (each boot
-- inserted it), and ON CONFLICT DO NOTHING never overwrites a default a super
-- admin changed through PUT /permissions/roles. A row that IS missing (a
-- database that never booted this release) is inserted, and the existing
-- mirror trigger carries it to the legacy-template org roles — exactly what
-- the next boot would have done.
--
-- A new legacy cell after this point ships as a migration like any other
-- capability change; nothing seeds at boot.

